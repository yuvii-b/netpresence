"""Export one classroom (netsim scene + channel realisation + protocol constants) for the OMNeT++ model in ../omnet.

    python -m netsim.omnet_export --preset class93 --seed 1 --out ../omnet/generated/scene

The room, the phones and the MEAN received power of every pair come from the same Python code as the Python simulator (same
seed -> same room and same shadowing), so the two simulators can be compared on identical classrooms. Everything that happens in
time is left to OMNeT++. Protocol constants are read from the real sources through sim.protocol, never copied by hand.
"""
from __future__ import annotations

import argparse
import random
from dataclasses import replace
from pathlib import Path

import numpy as np

from netsim import config, uplink
from netsim.attacks import add_relays
from netsim.channel import pair_mean_rssi
from netsim.scenario import build_scene
from sim import protocol


def build(cfg, seed: int, relays: int = 0):
    """(nodes, seeds, wall, M) with M the symmetric mean-RSSI matrix; mirrors synth_reports' random-stream layout."""
    rng = random.Random(seed)
    nodes, seeds, wall = build_scene(cfg, rng)
    clones = {}
    if relays:
        cand = [k for k, v in nodes.items() if v["inside"] and k not in seeds]
        acc = rng.sample(cand, min(relays, len(cand)))
        clones = dict(zip(add_relays(nodes, acc), acc))
    g_shadow, g_count, g_noise, g_det, g_tap, g_orient, g_up = (np.random.default_rng(x) for x in np.random.SeedSequence(rng.getrandbits(63)).spawn(7))
    iu, ju, d, mean = pair_mean_rssi(cfg, nodes, wall, g_shadow, g_orient)
    ids = list(nodes)
    N = len(ids)
    M = np.full((N, N), -200.0)
    M[iu, ju] = mean
    M[ju, iu] = mean
    pos = {k: i for i, k in enumerate(ids)}
    for f, a in clones.items():                         # one radio cannot hear itself
        M[pos[f], pos[a]] = M[pos[a], pos[f]] = -200.0
    return nodes, seeds, wall, M


def export(cfg, seed: int, out: str | Path, relays: int = 0) -> Path:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    nodes, seeds, wall, M = build(cfg, seed, relays)
    ids = list(nodes)
    wall_x, door = wall
    xs = [v["pos"][0] for v in nodes.values() if v["inside"]]
    ys = [v["pos"][1] for v in nodes.values() if v["inside"]]
    prm = {
        "window_s": cfg.window_s, "tail_s": cfg.tail_s, "grace_s": protocol.GRACE_S, "startup_s": cfg.startup_s,
        "tap_median_s": cfg.tap_median_s, "tap_sigma": cfg.tap_sigma,
        "min_samples": cfg.min_samples, "max_neighbours": protocol.MAX_NEIGHBOURS,
        "airtime_ms": cfg.airtime_ms, "t_ifs_adv_ms": cfg.t_ifs_adv_ms, "adv_delay_max_ms": cfg.adv_delay_max_ms,
        "p_bg_37": cfg.p_bg[0], "p_bg_38": cfg.p_bg[1], "p_bg_39": cfg.p_bg[2], "rician_k_db": cfg.rician_k_db,
        "sensitivity": cfg.sensitivity, "p_detect": cfg.p_detect, "dir_sigma": cfg.dir_sigma,
        "capture": int(cfg.capture), "capture_db": cfg.capture_db,
        "android_scan_window_ms": protocol.ANDROID_SCAN_WINDOW_MS, "android_scan_interval_ms": protocol.ANDROID_SCAN_INTERVAL_MS,
        "ios_scan_dwell_ms": cfg.ios_scan_dwell_ms, "ios_min_report_ms": cfg.ios_min_report_ms,
        "calibrate": 1,
        "retry_start_ms": protocol.RETRY_START_MS, "retry_max_ms": protocol.RETRY_MAX_MS,
        "request_timeout_ms": protocol.REQUEST_TIMEOUT_MS, "verify_ms": uplink.VERIFY_MS,
        "http_overhead_bytes": uplink.HTTP_OVERHEAD_BYTES, "conn_rtts": uplink.CONN_RTTS, "upload_jitter_s": cfg.upload_jitter_s,
        "uplink_mix": ";".join(f"{n}:{f}" for n, f in uplink.parse_mix(cfg.uplink if cfg.uplink != "ideal" else "ideal")),
        "room_w": round(max(xs) if xs else 1.0, 3), "room_d": round(max(ys) if ys else 1.0, 3), "wall_x": round(wall_x, 3),
        "door_y0": door[0] if door else -1, "door_y1": door[1] if door else -1,
        "seed": seed, "students": sum(1 for v in nodes.values() if v["inside"]),
        "service_prefix": protocol.SERVICE_PREFIX,
    }
    (out / "params.csv").write_text("# generated by netsim.omnet_export; protocol values read from the repo sources\n"
                                    + "".join(f"{k},{v}\n" for k, v in prm.items()), encoding="ascii")
    rows = ["idx,id,x,y,inside,seed,platform,rx,tx,adv_ms,scan_eff,tap_s"]
    for i, k in enumerate(ids):
        v, m = nodes[k], cfg.models[nodes[k]["model"]]
        rows.append(f"{i},{k},{v['pos'][0]:.3f},{v['pos'][1]:.3f},{int(v['inside'])},{int(k in seeds)},{m['platform']},"
                    f"{m['rx']},{m['tx']},{m['adv_ms']},{m['scan_eff']},{v.get('tap_s', -1)}")
    (out / "phones.csv").write_text("\n".join(rows) + "\n", encoding="ascii")
    (out / "models.csv").write_text("id,model,platform\n" + "".join(f"{k},{nodes[k]['model']},{cfg.models[nodes[k]['model']]['platform']}\n" for k in ids), encoding="ascii")
    (out / "seeds.csv").write_text("id\n" + "".join(f"{k}\n" for k in seeds), encoding="ascii")
    (out / "matrix.csv").write_text("\n".join(",".join(f"{x:.2f}" for x in row) for row in M) + "\n", encoding="ascii")
    prof = ["name,shared,rtt_ms,rtt_sigma,loss,cap_mbps,alpha,stall_p,blackout"]
    for n, p in uplink.PROFILES.items():
        prof.append(f"{n},{int(p['shared'])},{p['rtt_ms']},{p['rtt_sigma']},{p['loss']},{p['cap_mbps']},{p['alpha']},{p['stall_p']},{int(p.get('blackout', False))}")
    (out / "profiles.csv").write_text("\n".join(prof) + "\n", encoding="ascii")
    (out / "bytes.csv").write_text("n,bytes\n" + "".join(f"{n},{uplink.report_bytes(n)}\n" for n in range(protocol.MAX_NEIGHBOURS + 1)), encoding="ascii")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--preset", default="class93")
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--relays", type=int, default=0, help="relay attack: this many accomplice radios also carry an absent friend's id")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "omnet" / "generated" / "scene"))
    a = ap.parse_args(argv)
    cfg = config.load(a.preset, overrides=dict(s.split("=", 1) for s in a.set) or None)
    p = export(cfg, a.seed, a.out, a.relays)
    print(f"scene written to {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
