"""Regenerate every figure, table and number of the paper from code.

    python -m paper.make --quick                 # every experiment with few classrooms (CI, ~1-2 min)
    python -m paper.make                         # full run (publication numbers, ~15-20 min on 4 cores)
    python -m paper.make --only E03,E06 --workers 4

Writes paper/out/{results/*.json, results/hashes.json, tables/*.md|.tex, figures/*.pdf|.png, summary.md}. Results are cached by
configuration + code fingerprint (paper/out/cache), so re-running recomputes only what changed. hashes.json holds one hash per
experiment over its deterministic content (timings excluded); CI compares it between Windows and Linux.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from netsim import config, plots
from netsim.experiments import Ctx, load
from netsim.runner import Cache, code_fingerprint, digest, round_floats

HERE = Path(__file__).resolve().parent


def deterministic_part(result: dict) -> dict:
    return {k: v for k, v in result.items() if k != "timing"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true", help="few classrooms per point; every experiment still runs")
    ap.add_argument("--only", help="comma-separated experiment ids, e.g. E03,E06")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--out", default=str(HERE / "out"))
    ap.add_argument("--real", default=str(HERE / "real"), help="folder with measurements from real phones (E12, E13)")
    ap.add_argument("--no-figures", action="store_true")
    ap.add_argument("--no-cache", action="store_true")
    a = ap.parse_args(argv)

    out = Path(a.out)
    for sub in ("results", "tables", "figures"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    ctx = Ctx(quick=a.quick, workers=a.workers, cache=Cache(None if a.no_cache else out / "cache"), real_dir=a.real)
    wanted = [w.strip() for w in a.only.split(",")] if a.only else [None]
    exps = []
    for w in wanted:
        exps += load(w)
    figures = plots.available() and not a.no_figures
    if not figures and not a.no_figures:
        print("matplotlib not installed: tables and numbers are written, figures are skipped (pip install matplotlib)")

    hashes, sections, t_all = {}, [], time.time()
    for exp in exps:
        t0 = time.time()
        res = exp["run"](ctx)
        res = round_floats(json.loads(json.dumps(res)))
        res["timing"] = {**res.get("timing", {}), "seconds": round(time.time() - t0, 2)}
        (out / "results" / f"{exp['id']}.json").write_text(json.dumps(res, indent=1, sort_keys=True), encoding="utf-8")
        hashes[exp["id"]] = digest(deterministic_part(res))
        md, tex = exp["table"](res)
        (out / "tables" / f"{exp['id']}.md").write_text(md + "\n", encoding="utf-8")
        (out / "tables" / f"{exp['id']}.tex").write_text(tex, encoding="utf-8")
        figs = exp["plot"](res, out / "figures") if figures else []
        sections.append(f"## {exp['id']} {exp['title']}\n\n*{exp['question']}*\n\n{md}\n\n" + "".join(f"![{f}](figures/{f})\n" for f in figs if f.endswith(".png")))
        print(f"{exp['id']}  {exp['title']:<38} {res['timing']['seconds']:>6.1f} s  hash {hashes[exp['id']][:10]}", flush=True)

    (out / "results" / "hashes.json").write_text(json.dumps({"quick": a.quick, "code": code_fingerprint(), "hashes": hashes},
                                                            indent=1, sort_keys=True), encoding="utf-8")
    assumed = ", ".join(config.assumed_fields())
    head = (f"# NetPresence network simulator: results ({'QUICK, few classrooms' if a.quick else 'full'})\n\n"
            f"Code fingerprint `{code_fingerprint()}`. Every number below is regenerated by `python -m paper.make`; nothing is typed by hand.\n\n"
            f"**Provenance.** Radio, human-timing and baseline parameters are assumptions until measured (SIM_PLAN section 5). "
            f"Assumed configuration fields: {assumed}. E12 and E13 say explicitly whether real or synthetic data was used.\n\n")
    (out / "summary.md").write_text(head + "\n".join(sections), encoding="utf-8")
    print(f"done in {time.time() - t_all:.0f} s -> {out}  (cache hits {ctx.cache.hits}, misses {ctx.cache.misses})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
